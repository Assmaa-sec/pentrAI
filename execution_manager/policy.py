"""Base per-scan Kubernetes policy objects for the isolated execution cluster.

These objects are deliberately closed: workload traffic needs separate,
reviewed allow rules and a staging containment proof before any dynamic job.
"""

from __future__ import annotations

import re

from control_plane.models import RunnerLease


_NAMESPACE = re.compile(r"^scan-[0-9a-f]{32}$")


def base_namespace_objects(lease: RunnerLease) -> tuple[dict, ...]:
    """Return admission, quota, and default-deny objects for one lease."""
    if not _NAMESPACE.fullmatch(lease.namespace):
        raise ValueError("lease namespace is not generated by PentrAI")
    if lease.service_account != "scan-runner":
        raise ValueError("unexpected runner service account")
    namespace = lease.namespace
    labels = {
        "pentrai.io/lease-id": lease.id,
        "pod-security.kubernetes.io/enforce": "restricted",
        "pod-security.kubernetes.io/audit": "restricted",
        "pod-security.kubernetes.io/warn": "restricted",
    }
    return (
        {
            "apiVersion": "v1", "kind": "Namespace",
            "metadata": {"name": namespace, "labels": labels},
        },
        {
            "apiVersion": "v1", "kind": "ServiceAccount",
            "metadata": {"name": lease.service_account, "namespace": namespace},
            "automountServiceAccountToken": False,
        },
        {
            "apiVersion": "v1", "kind": "ResourceQuota",
            "metadata": {"name": "scan-budget", "namespace": namespace},
            "spec": {"hard": {
                "requests.cpu": "2", "requests.memory": "4Gi",
                "limits.cpu": "4", "limits.memory": "8Gi",
                "pods": "8", "persistentvolumeclaims": "1",
                "requests.storage": "512Mi",
                "services": "2", "secrets": "4",
            }},
        },
        {
            "apiVersion": "v1", "kind": "LimitRange",
            "metadata": {"name": "container-budget", "namespace": namespace},
            "spec": {"limits": [{
                "type": "Container",
                "defaultRequest": {"cpu": "100m", "memory": "128Mi"},
                "default": {"cpu": "500m", "memory": "512Mi"},
                "max": {"cpu": "2", "memory": "2Gi"},
            }]},
        },
        {
            "apiVersion": "networking.k8s.io/v1", "kind": "NetworkPolicy",
            "metadata": {"name": "default-deny", "namespace": namespace},
            "spec": {"podSelector": {}, "policyTypes": ["Ingress", "Egress"],
                     "ingress": [], "egress": []},
        },
    )
